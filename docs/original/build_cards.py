def wrap(d,text,f,maxw):
    words=text.split(' ');lines=[];cur=''
    for w in words:
        t=(cur+' '+w).strip()
        if d.textlength(t,font=f)<=maxw: cur=t
        else: lines.append(cur);cur=w
    if cur: lines.append(cur)
    return lines
def chip(d,x,y,text,f,col,maxx):
    tw=d.textlength(text,font=f);w=tw+60;h=92
    if x+w>maxx: x=120;y+=h+22
    d.rounded_rectangle([x,y,x+w,y+h],radius=24,fill=(30,36,52),outline=col,width=3)
    d.text((x+30,y+h/2),text,font=f,fill=(255,255,255),anchor='lm')
    return x+w+20,y
